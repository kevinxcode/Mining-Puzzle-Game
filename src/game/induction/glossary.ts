/**
 * Site Induction — glossary of common haul-operation terms (plain language).
 */

import type { GlossaryTerm } from './types';

export const GLOSSARY: GlossaryTerm[] = [
  { term: 'Bucket pass', definition: 'One scoop of material that the excavator drops into a truck. A truck is usually filled in a few passes.' },
  { term: 'Cycle time', definition: 'The total time for one full trip: load, haul, dump and return to the loading point.' },
  { term: 'Dump point', definition: 'The place where trucks unload, such as a crusher, stockpile or waste dump.' },
  { term: 'Haul road', definition: 'A road built for heavy trucks to carry material between the pit and the dump point.' },
  { term: 'Loaded truck', definition: 'A truck carrying material. It is heavy and slow to stop, so it gets right of way.' },
  { term: 'Ore', definition: 'Rock or material that contains something valuable and is sent for processing.' },
  { term: 'Overburden', definition: 'Waste rock and soil on top of the ore that must be removed first and taken to a waste dump.' },
  { term: 'Payload', definition: 'The weight of material a truck carries on one trip, measured in tonnes.' },
  { term: 'Pre-start check', definition: 'A walk-around inspection of a machine before the shift: tyres, lights, brakes, leaks, fluids and alarms.' },
  { term: 'Production rate', definition: 'How much material is moved over time, usually tonnes per hour.' },
  { term: 'Queue time', definition: 'Time a truck spends waiting in line to be loaded or to dump.' },
  { term: 'Idle time', definition: 'Time a machine is running but not doing useful work, such as waiting with nothing to load.' },
  { term: 'Refuelling', definition: 'Stopping at the fuel bay to top up. Planned refuels avoid trucks running dry on the road.' },
  { term: 'Right of way', definition: 'The rule for who goes first. On haul roads, loaded trucks and emergency vehicles usually go first.' },
  { term: 'Spotting', definition: 'Positioning a truck in the right place next to the excavator so it can be loaded safely and quickly.' },
  { term: 'Truck matching', definition: 'Pairing trucks with an excavator so full loads take a whole number of bucket passes.' },
  { term: 'Utilization', definition: 'The share of time equipment spends working instead of waiting. Higher is better.' },
  { term: 'Windrow', definition: 'A berm (pile of material) along the edge of a haul road that helps stop vehicles from leaving the road.' },
];
